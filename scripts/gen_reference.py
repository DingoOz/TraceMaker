"""Generates the reference pages of the documentation site that must never drift from the code (D134).

  scripts/gen_reference.py cli   --build build/release [--check]   # docs/reference/cli.md from the programs' --help
  scripts/gen_reference.py bench [--check]                          # docs/reference/benchmarks.md from bench/records

The pages are committed, so they read the same on GitHub and on the site. `--check` writes nothing and exits 1 when
the committed page differs from what the code produces now (CI runs it after the build); run without it to update.
"""
import argparse
import json
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REPO = "https://github.com/DingoOz/TraceMaker"
HEADER = "<!-- Generated by scripts/gen_reference.py {what}; do not edit by hand. -->\n\n"

# The programs and the subcommands of `tracemaker`, in the order of its own --help.
PROGRAMS = [("tracemaker", "src/app/tracemaker"), ("tracemaker-place", "src/place/tracemaker-place"),
            ("tracemaker-view", "src/server/tracemaker-view")]


def help_text(binary: str, name: str, args: list[str]) -> str:
    out = subprocess.run([binary, *args, "--help"], capture_output=True, text=True, timeout=60)
    text = out.stdout or out.stderr
    text = text.replace(binary, name)
    return "\n".join(line.rstrip() for line in text.strip("\n").split("\n"))


def subcommands(top_help: str) -> list[str]:
    names, inside = [], False
    for line in top_help.split("\n"):
        if line.startswith("SUBCOMMANDS:"):
            inside = True
            continue
        if inside:
            m = re.match(r"^  (\S+)\s", line)
            if m:
                names.append(m.group(1))
            elif line and not line.startswith(" "):
                break
    return names


def cli_page(build: str) -> str:
    parts = [HEADER.format(what="cli"), "# Command line\n\n",
             "Every option of every program, as its own `--help` prints it. This page is generated from the build, so it\n"
             "is what the code accepts; the README's *Common tasks* table says which options to reach for first.\n\n"]
    for name, rel in PROGRAMS:
        binary = os.path.join(build, rel)
        if not os.access(binary, os.X_OK):
            sys.exit(f"gen_reference: {binary} is missing; build first")
        top = help_text(binary, name, [])
        parts.append(f"## `{name}`\n\n```text\n{top}\n```\n\n")
        for sub in subcommands(top) if name == "tracemaker" else []:
            parts.append(f"### `{name} {sub}`\n\n```text\n{help_text(binary, name, [sub])}\n```\n\n")
    return "".join(parts).rstrip("\n") + "\n"


def pct(x) -> str:
    return "" if x is None else f"{100 * x:.1f}%"


def bench_page() -> str:
    records = os.path.join(ROOT, "bench", "records")
    groups: dict[str, list[tuple[str, dict]]] = {}
    for dirpath, _, filenames in os.walk(records):
        if "summary.json" in filenames:
            path = os.path.join(dirpath, "summary.json")
            with open(path) as f:
                summary = json.load(f)
            if isinstance(summary.get("run"), dict):
                continue  # a single route's summary (`route --json`, D136), not a benchmark run
            record = os.path.relpath(path, records).split(os.sep)[0]
            groups.setdefault(record, []).append((os.path.relpath(dirpath, ROOT), summary))
    parts = [HEADER.format(what="bench"), "# Benchmark results\n\n",
             "Every benchmark run whose `summary.json` is kept in `bench/records/`, grouped by record. *Clean* is the share\n"
             "of boards with every connection made and no error added in KiCad's DRC (the judge of D8 and, since\n"
             "2026-10-14, D106); *FR 2.5* is Freerouting 2.5.0-RC12's published result on the same boards. Each record's\n"
             "README says what the runs were for and how to read them; numbers from different records are not always\n"
             "comparable (judge version, time limit, machine load).\n\n"]
    for record in sorted(groups):
        parts.append(f"## {record}\n\n[Record and README]({REPO}/tree/main/bench/records/{record})\n\n")
        parts.append("| Run | Set | Boards | Commit | Clean | Completion | FR 2.5 | Seconds | Route options |\n"
                     "|---|---|--:|---|--:|--:|--:|--:|---|\n")
        for path, s in sorted(groups[record], key=lambda r: r[0]):
            run = s.get("run") or os.path.basename(path)
            args = s.get("route_args")
            parts.append(f"| [{run}]({REPO}/blob/main/{path}/summary.json) | {s.get('set', '')} | {s.get('boards', '')} | "
                         f"{s.get('commit') or ''} | {pct(s.get('clean_pass'))} | {pct(s.get('completion'))} | "
                         f"{pct(s.get('fr_rc12_clean_pass'))} | {round(s['seconds']) if s.get('seconds') else ''} | "
                         f"{'`' + args + '`' if args else ''} |\n")
        parts.append("\n")
    return "".join(parts).rstrip("\n") + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("page", choices=["cli", "bench"])
    ap.add_argument("--build", default=os.path.join(ROOT, "build", "release"), help="build directory (cli)")
    ap.add_argument("--check", action="store_true", help="fail if the committed page is out of date")
    a = ap.parse_args()
    text = cli_page(a.build) if a.page == "cli" else bench_page()
    path = os.path.join(ROOT, "docs", "reference", "cli.md" if a.page == "cli" else "benchmarks.md")
    old = open(path).read() if os.path.exists(path) else ""
    if a.check:
        if old != text:
            print(f"{os.path.relpath(path, ROOT)} is out of date: run scripts/gen_reference.py {a.page}", file=sys.stderr)
            return 1
        return 0
    if old != text:
        with open(path, "w") as f:
            f.write(text)
        print(f"wrote {os.path.relpath(path, ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
