"""The decision log (D134): one Architecture Decision Record per decision in docs/decisions/, and the index table
in docs/12-decisions.md generated from them (Nygard, "Documenting architecture decisions", 2011).

  scripts/decisions.py new "Title" [--number N] [--docs 05,10]   # next free number from the template; prints the path
  scripts/decisions.py index                                     # regenerate the index in docs/12-decisions.md
  scripts/decisions.py check                                     # CI: records well formed, index up to date
  scripts/decisions.py import [--title D132="Short title" ...]    # rows `| D132 | decision | alternatives | reason |`
                                                                 # left in docs/12-decisions.md become records

`import` is how a decision written the old way (a table row appended to docs/12-decisions.md, e.g. on a branch
started before the records existed) becomes a record: the row is removed from the table and the index regenerated.
A row without --title gets its first clause as the title; edit it afterwards.
"""
import argparse
import datetime
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "docs")
DIR = os.path.join(DOCS, "decisions")
INDEX = os.path.join(DOCS, "12-decisions.md")
TEMPLATE = os.path.join(DIR, "_template.md")
BEGIN = "<!-- BEGIN decision index: generated by scripts/decisions.py index; edit the records, not this table -->"
END = "<!-- END decision index -->"
STATUSES = ("proposed", "accepted", "superseded", "rejected")
# Numbers used on unmerged branches, listed in the index so nobody takes them again.
RESERVED = {87: "reserved by PR #21 (probe sealed BGA targets first), not merged"}


def file_name(n: int) -> str:
    return f"D{n:03d}.md"


def parse_front_matter(text: str) -> tuple[dict, str]:
    m = re.match(r"^---\n(.*?)\n---\n", text, re.S)
    if not m:
        return {}, text
    meta = {}
    for line in m.group(1).split("\n"):
        key, _, value = line.partition(":")
        value = value.strip()
        if value.startswith("["):
            value = [v.strip().strip('"') for v in value.strip("[]").split(",") if v.strip()]
        else:
            value = value.strip('"')
        meta[key.strip()] = value
    return meta, text[m.end():]


def front_matter(meta: dict) -> str:
    lines = []
    for key, value in meta.items():
        if isinstance(value, list):
            value = "[" + ", ".join(f'"{v}"' if key == "docs" else v for v in value) + "]"
        elif key == "title":
            value = json.dumps(value, ensure_ascii=False)
        lines.append(f"{key}: {value}")
    return "---\n" + "\n".join(lines) + "\n---\n"


def records() -> dict[int, tuple[str, dict]]:
    out = {}
    for name in sorted(os.listdir(DIR)):
        m = re.fullmatch(r"D(\d+)\.md", name)
        if m:
            with open(os.path.join(DIR, name)) as f:
                meta, _ = parse_front_matter(f.read())
            out[int(m.group(1))] = (name, meta)
    return out


def status_cell(meta: dict) -> str:
    status = meta.get("status", "")
    if status == "superseded" and meta.get("superseded_by"):
        sid = int(meta["superseded_by"].lstrip("D"))
        return f"superseded by [{meta['superseded_by']}](decisions/{file_name(sid)})"
    return status


def index_table() -> str:
    rows = ["| # | Decision | Status |", "|---|---|---|"]
    recs = records()
    for n in sorted(set(recs) | set(RESERVED)):
        if n in recs:
            name, meta = recs[n]
            rows.append(f"| [D{n}](decisions/{name}) | {meta.get('title', '')} | {status_cell(meta)} |")
        else:
            rows.append(f"| D{n} (reserved) | *{RESERVED[n]}* | |")
    return "\n".join(rows)


def render_index(text: str) -> str:
    start, end = text.index(BEGIN) + len(BEGIN), text.index(END)
    return text[:start] + "\n" + index_table() + "\n" + text[end:]


def cmd_index() -> int:
    with open(INDEX) as f:
        old = f.read()
    new = render_index(old)
    if new != old:
        with open(INDEX, "w") as f:
            f.write(new)
        print("updated docs/12-decisions.md")
    return 0


def cmd_check() -> int:
    errors = []
    recs = records()
    for n, (name, meta) in recs.items():
        if meta.get("id") != f"D{n}":
            errors.append(f"{name}: id is {meta.get('id')!r}, expected 'D{n}'")
        if not meta.get("title"):
            errors.append(f"{name}: no title")
        if meta.get("status") not in STATUSES:
            errors.append(f"{name}: status {meta.get('status')!r} is not one of {', '.join(STATUSES)}")
        sup = meta.get("superseded_by")
        if (meta.get("status") == "superseded") != bool(sup):
            errors.append(f"{name}: a superseded record needs superseded_by, and only a superseded one")
        if sup and int(sup.lstrip("D")) not in recs:
            errors.append(f"{name}: superseded_by {sup} has no record")
        for d in meta.get("docs", []):
            if not any(f.startswith(f"{d}-") for f in os.listdir(DOCS)):
                errors.append(f"{name}: docs lists {d}, which is no design doc")
    with open(INDEX) as f:
        text = f.read()
    if render_index(text) != text:
        errors.append("docs/12-decisions.md: the index is out of date; run scripts/decisions.py index")
    if re.search(r"^\| D\d+ \|", text, re.M):
        errors.append("docs/12-decisions.md: a decision row in the old table format; run scripts/decisions.py import")
    for e in errors:
        print(e, file=sys.stderr)
    return 1 if errors else 0


def cmd_new(title: str, number: int | None, docs: list[str]) -> int:
    recs = records()
    n = number or max(set(recs) | set(RESERVED)) + 1
    if n in recs or n in RESERVED:
        sys.exit(f"D{n} exists")
    with open(TEMPLATE) as f:
        _, body = parse_front_matter(f.read())
    meta = {"id": f"D{n}", "title": title, "status": "accepted", "date": datetime.date.today().isoformat(), "docs": docs}
    path = os.path.join(DIR, file_name(n))
    with open(path, "w") as f:
        f.write(front_matter(meta) + body.replace("{id}", f"D{n}").replace("{title}", title))
    cmd_index()
    print(os.path.relpath(path, ROOT))
    return 0


def split_row(line: str) -> list[str]:
    # Cells are separated by '|' outside backticks (rows hold code spans such as `a || b`).
    cells, cur, code = [], "", False
    for ch in line.strip().strip("|"):
        if ch == "`":
            code = not code
        if ch == "|" and not code:
            cells.append(cur.strip())
            cur = ""
        else:
            cur += ch
    cells.append(cur.strip())
    return cells


def record_text(n: int, title: str, cells: list[str], meta_extra: dict, headings=("Alternatives", "Reason")) -> str:
    meta = {"id": f"D{n}", "title": title, "status": meta_extra.get("status", "accepted")}
    if meta_extra.get("superseded_by"):
        meta["superseded_by"] = meta_extra["superseded_by"]
    meta["relates"] = meta_extra.get("relates", [])
    meta["docs"] = meta_extra.get("docs", [])
    body = f"# D{n} — {title}\n\n"
    if meta["status"] == "superseded":
        sid = int(meta["superseded_by"].lstrip("D"))
        body += f"!!! warning \"Superseded by [{meta['superseded_by']}]({file_name(sid)})\"\n\n"
    body += f"## Decision\n\n{cells[0]}\n"
    for heading, cell in zip(headings, cells[1:]):  # a row may lack the last column (D92 has no reason)
        body += f"\n## {heading}\n\n{cell}\n"
    if meta["relates"]:
        body += "\n## Related\n\n" + ", ".join(f"[{r}]({file_name(int(r[1:]))})" for r in meta["relates"]) + "\n"
    return front_matter(meta) + "\n" + body


def first_clause(text: str) -> str:
    text = re.sub(r"\s*\(doc[^)]*\)", "", text)
    clause = re.split(r"(?<=[a-z0-9`)])[.;:] ", text, maxsplit=1)[0]
    words = clause.split()
    return " ".join(words[:9]).rstrip(",.;:") + ("…" if len(words) > 9 else "")


def cmd_import(titles: dict[str, str], meta_file: str | None, headings: dict[int, tuple[str, str]]) -> int:
    extra = {}
    if meta_file:
        with open(meta_file) as f:
            extra = json.load(f)
    with open(INDEX) as f:
        lines = f.read().split("\n")
    kept, rows, made = [], [], []
    for line in lines:
        m = re.match(r"^\| D(\d+) \|", line)
        if not m:
            kept.append(line)
            continue
        n = int(m.group(1))
        cells = split_row(line)[1:]
        if len(cells) not in (2, 3):
            sys.exit(f"D{n}: expected 3 or 4 cells, found {len(cells) + 1}; nothing was written")
        if os.path.exists(os.path.join(DIR, file_name(n))):
            sys.exit(f"docs/decisions/{file_name(n)} exists, so D{n} is taken; renumber the row; nothing was written")
        rows.append((n, cells))
    for n, cells in rows:
        info = extra.get(f"D{n}", {})
        title = titles.get(f"D{n}") or info.get("title") or first_clause(cells[0])
        with open(os.path.join(DIR, file_name(n)), "w") as f:
            f.write(record_text(n, title, cells, info, headings.get(n, ("Alternatives", "Reason"))))
        made.append(f"D{n}: {title}")
    with open(INDEX, "w") as f:
        f.write("\n".join(kept))
    cmd_index()
    for line in made:
        print("made", line)
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("new")
    p.add_argument("title")
    p.add_argument("--number", type=int)
    p.add_argument("--docs", default="", help="design docs this decision changes, e.g. 05,10")
    sub.add_parser("index")
    sub.add_parser("check")
    p = sub.add_parser("import")
    p.add_argument("--title", action="append", default=[], metavar="DNNN=TITLE")
    p.add_argument("--meta", help=argparse.SUPPRESS)  # JSON {"D1": {title, status, superseded_by, relates, docs}}
    p.add_argument("--headings", help=argparse.SUPPRESS)  # JSON {"124": ["Reason", "Consequences"]}
    a = ap.parse_args()
    if a.cmd == "new":
        return cmd_new(a.title, a.number, [d for d in a.docs.split(",") if d])
    if a.cmd == "index":
        return cmd_index()
    if a.cmd == "check":
        return cmd_check()
    titles = dict(t.split("=", 1) for t in a.title)
    headings = {int(k): tuple(v) for k, v in json.loads(a.headings).items()} if a.headings else {}
    return cmd_import(titles, a.meta, headings)


if __name__ == "__main__":
    sys.exit(main())
